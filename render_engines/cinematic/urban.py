def water_body(name: str, location, size, col=None):
    """Ocean surface: deep blue, glossy, with moving procedural waves (bump), opaque for speed."""
    mat = bpy.data.materials.new(f"{name}_water")
    mat.use_nodes = True
    nodes, links = mat.node_tree.nodes, mat.node_tree.links
    bsdf = nodes["Principled BSDF"]
    bsdf.inputs["Base Color"].default_value = hex_to_linear("#1d5c86")
    bsdf.inputs["Roughness"].default_value = 0.08
    bsdf.inputs["Coat Weight"].default_value = 0.6
    coord = nodes.new("ShaderNodeTexCoord")
    mapping = nodes.new("ShaderNodeMapping")
    mapping.name = "Waves"
    links.new(coord.outputs["Object"], mapping.inputs["Vector"])
    noise = nodes.new("ShaderNodeTexNoise")
    noise.inputs["Scale"].default_value = 0.35
    noise.inputs["Detail"].default_value = 6.0
    links.new(mapping.outputs["Vector"], noise.inputs["Vector"])
    bump = nodes.new("ShaderNodeBump")
    bump.inputs["Strength"].default_value = 0.6
    links.new(noise.outputs["Fac"], bump.inputs["Height"])
    links.new(bump.outputs["Normal"], bsdf.inputs["Normal"])
    foam = nodes.new("ShaderNodeValToRGB")
    foam.color_ramp.elements[0].position = 0.68
    foam.color_ramp.elements[0].color = (0, 0, 0, 1)
    foam.color_ramp.elements[1].position = 0.75
    links.new(noise.outputs["Fac"], foam.inputs["Fac"])
    mix = nodes.new("ShaderNodeMix")
    mix.data_type = "RGBA"
    mix.inputs["A"].default_value = hex_to_linear("#1d5c86")
    mix.inputs["B"].default_value = hex_to_linear("#e8f2f5")
    links.new(foam.outputs["Color"], mix.inputs["Factor"])
    links.new(mix.outputs["Result"], bsdf.inputs["Base Color"])
    plane = objects.mesh_object(name, _box(size[0], size[1], 2.0, (0, 0, -1.0)), mat, location=location, col=col)
    plane.visible_shadow = False
    return plane


def animate_waves(water, start: int, end: int, speed=(0.0, 0.6, 0.0)) -> None:
    mapping = water.active_material.node_tree.nodes["Waves"]
    socket = mapping.inputs["Location"]
    socket.default_value = (0, 0, 0)
    socket.keyframe_insert("default_value", frame=start)
    span = (end - start) / 24
    socket.default_value = (speed[0] * span, speed[1] * span, speed[2] * span)
    socket.keyframe_insert("default_value", frame=end)


def surge(urban: Urban, start: int, end: int, height: float, inland: float) -> None:
    """The sea comes ashore: the water body rises and advances into the street."""
    water = urban.water
    x, y, z = water.location
    key(water, "location", start, (x, y, z))
    key(water, "location", end, (x, y + inland, z + height))
    set_interpolation(water, "LINEAR")
    animate_waves(water, start, end, (0.4, 1.5, 0.3))


def shatter_windows(urban: Urban, start: int, fps: int, stagger: float = 0.25) -> None:
    """Glass panes break (rigid-body shards released, slightly staggered floor by floor)."""
    rng = random.Random(len(urban.panes))
    for k, shards in enumerate(urban.panes):
        frame = start + round(rng.uniform(0, stagger) * fps) + (k % 3)
        for shard in shards:
            shard.rigid_body.kinematic = True
            shard.rigid_body.keyframe_insert("kinematic", frame=1)
            shard.rigid_body.keyframe_insert("kinematic", frame=frame - 1)
            shard.rigid_body.kinematic = False
            shard.rigid_body.keyframe_insert("kinematic", frame=frame)


def lights_on(urban: Urban, start: int, end: int, windows: float = 0.45) -> None:
    for mat in urban.facades:
        socket = mat.node_tree.nodes["Lights"].outputs[0]
        socket.keyframe_insert("default_value", frame=start)
        socket.default_value = windows
        socket.keyframe_insert("default_value", frame=end)
    for head in urban.lamp_heads:
        socket = head.node_tree.nodes["Principled BSDF"].inputs["Emission Strength"]
        socket.keyframe_insert("default_value", frame=start)
        socket.default_value = 6.0
        socket.keyframe_insert("default_value", frame=end)


