def build_interior(env: dict, ctx, scene, seed: int) -> Urban:
    """A living room: wooden floor, painted walls, a window to the street, furniture that physics can move.
    Room spans x in [-3, 3] (east wall at +3), y in [-2.5, 2.5], height 2.7; the camera usually looks north."""
    rng = random.Random(seed)
    urban = Urban()
    col = objects.collection("Interior")
    room = env.get("room") if env.get("room") in ROOMS else "living_room"
    dark, light = rng.choice(ROOM_FLOORS[room])
    tiles = room == "kitchen"
    floor = materials.noise_ground(
        f"floor_{room}", dark, light, scale=14.0 if tiles else 6.0, roughness=0.35 if tiles else 0.6, bump=0.15
    )
    wall = _mat("wall_paint", env.get("wall_color") or rng.choice(WALL_COLORS), roughness=0.9)
    trim = _mat("trim", "#f4f1ea", roughness=0.6)
    urban.static = [objects.mesh_object("Floor", _box(6.4, 5.4, 0.1, (0, 0, -0.05)), floor, col=col)]
    walls = [
        ((0, 2.75, 1.35), (6.4, 0.1, 2.7)),
        ((3.15, 0, 1.35), (0.1, 5.4, 2.7)),
        ((-3.15, 0, 1.35), (0.1, 5.4, 2.7)),
    ]
    for i, (at, size) in enumerate(walls):
        if i == 0:  # north wall with a window opening (x in [-0.9, 0.9], z in [0.9, 2.2])
            for at2, size2 in (
                ((-2.05, 2.75, 1.35), (2.3, 0.1, 2.7)),
                ((2.05, 2.75, 1.35), (2.3, 0.1, 2.7)),
                ((0, 2.75, 0.45), (1.8, 0.1, 0.9)),
                ((0, 2.75, 2.45), (1.8, 0.1, 0.5)),
            ):
                urban.static.append(objects.mesh_object(f"wall_n_{at2[0]}_{at2[2]}", _box(*size2, at2), wall, col=col))
        else:
            urban.static.append(objects.mesh_object(f"wall_{i}", _box(*size, at), wall, col=col))
    objects.mesh_object("Ceiling", _box(6.4, 5.4, 0.1, (0, 0, 2.75)), trim, col=col)
    glass = materials.principled("window_glass", "#cfe3ee", roughness=0.02, transmission=0.9)
    urban.window = objects.mesh_object("Window", _box(1.8, 0.03, 1.3, (0, 2.75, 1.55)), glass, col=col)

    from render_engines.cinematic.rooms import ROOM_BUILDERS  # rooms reuse this module's helpers

    ROOM_BUILDERS.get(room, _living_room)(urban, rng, col)
    urban.sky_refs = _sky({"time_of_day": env.get("time_of_day", "day")}, scene)
    ceiling = lights.area("Ceiling light", (0, 0, 2.6), (0, 0, 0), "#ffe3c0", env.get("room_light", 120), size=1.5)
    urban.sky_refs["room_light"] = ceiling
    # Light through the window.
    lights.area("Window light", (0, 3.6, 1.6), (math.radians(90), 0, 0), "#e9f2ff", 260, size=1.8)
    return urban


def _living_room(urban: Urban, rng, col) -> None:
    fabric = _mat("sofa_fabric", rng.choice(("#3f5e7a", "#7a4a3f", "#5a6b3f")), roughness=0.9)
    wood = _mat("furniture_wood", "#6b4a2e", roughness=0.55)
    white = _mat("furniture_white", "#ecebe6", roughness=0.5)
    sofa = compound(
        "sofa",
        [
            (_box(2.2, 0.9, 0.45, (0, 0, 0.22)), fabric),
            (_box(2.2, 0.2, 0.5, (0, 0.35, 0.7)), fabric),
            (_box(0.2, 0.9, 0.3, (1.0, 0, 0.6)), fabric),
            (_box(0.2, 0.9, 0.3, (-1.0, 0, 0.6)), fabric),
        ],
        (-0.6, 1.6, 0),
        col=col,
    )
    table = compound(
        "coffee_table",
        [(_box(1.1, 0.6, 0.06, (0, 0, 0.42)), wood)]
        + [(_box(0.05, 0.05, 0.4, (x, y, 0.2)), wood) for x in (-0.5, 0.5) for y in (-0.25, 0.25)],
        (-0.6, 0.5, 0),
        col=col,
    )
    # Open bookshelf against the west wall: back, sides and three shelves (books sit ON the shelves).
    shelf_parts = [
        (_box(0.04, 1.4, 2.0, (-0.15, 0, 1.0)), white),
        (_box(0.34, 0.04, 2.0, (0, -0.7, 1.0)), white),
        (_box(0.34, 0.04, 2.0, (0, 0.7, 1.0)), white),
    ]
    shelf_parts += [(_box(0.34, 1.4, 0.03, (0, 0, h)), white) for h in (0.02, 0.62, 1.22, 1.82)]
    shelf = compound("bookshelf", shelf_parts, (-2.9, 0.9, 0), col=col)
    tv_stand = compound("tv_stand", [(_box(0.4, 1.6, 0.5, (0, 0, 0.25)), wood)], (2.85, 0.4, 0), col=col)
    tv = compound(
        "tv",
        [(_box(0.06, 1.3, 0.75, (0, 0, 0.375)), _mat("tv_black", "#101114", roughness=0.2))],
        (2.85, 0.4, 0.52),
        col=col,
    )
    lamp = compound(
        "floor_lamp",
        [(_cyl(0.03, 1.6, (0, 0, 0.8)), white), (objects.cone(0.25, 0.15, 0.3, 16, base_at_origin=False), white)],
        (1.9, 2.2, 0),
        col=col,
    )
    plant = compound(
        "plant",
        [
            (_cyl(0.18, 0.4, (0, 0, 0.2)), _mat("pot", "#b5653c", roughness=0.8)),
            (
                objects.transform(objects.icosphere(0.35, 2), Matrix.Translation((0, 0, 0.75))),
                _mat("plant_leaf", "#3f7a35", roughness=0.8),
            ),
        ],
        (-2.4, 2.2, 0),
        col=col,
    )
    chairs = [
        compound(
            f"chair_{i}",
            [(_box(0.45, 0.45, 0.05, (0, 0, 0.45)), wood), (_box(0.45, 0.05, 0.5, (0, 0.2, 0.7)), wood)]
            + [(_box(0.04, 0.04, 0.45, (x, y, 0.22)), wood) for x in (-0.2, 0.2) for y in (-0.2, 0.2)],
            (0.9 + i * 0.7, -0.4, 0),
            col=col,
        )
        for i in range(2)
    ]
    urban.loose += [(sofa, 60), (table, 15), (tv_stand, 25), (tv, 12), (lamp, 4), (plant, 6)]
    urban.static.append(shelf)  # fixed to the wall
    urban.loose += [(c, 5) for c in chairs]
    book_colors = ("#b3261e", "#1f4e8c", "#d9a400", "#2e7d4f", "#e8e2d4", "#6b3fa0")
    for i in range(18):  # standing on the shelves, plus a few on the coffee table
        if i < 15:
            shelf_level, slot = divmod(i, 5)
            loc = (-2.85, 0.4 + slot * 0.2, 0.64 + shelf_level * 0.6 + 0.005)
        else:
            loc = (-0.9 + (i - 15) * 0.25, 0.5, 0.46)
        book = compound(
            f"book_{i}",
            [(_box(0.18, 0.05, 0.25, (0, 0, 0.125)), _mat(f"book_{i % 6}", book_colors[i % 6], roughness=0.7))],
            loc,
            col=col,
        )
        urban.loose.append((book, 0.6))


def enable_physics(urban: Urban, scene, ctx) -> None:
    ensure_rigid_world(scene, ctx.frame_start, ctx.frame_end)
    for obj in urban.static:
        make_rigid(obj, "PASSIVE", friction=0.7)
    for obj, mass in urban.loose:
        make_rigid(obj, "ACTIVE", mass=mass, friction=0.5)
    for shards in urban.panes:
        for shard in shards:
            make_rigid(shard, "ACTIVE", mass=0.4, friction=0.4)
            shard.rigid_body.kinematic = True  # held in its frame until it shatters
