# --- physics -----------------------------------------------------------------------------
def ensure_rigid_world(scene, frame_start: int, frame_end: int):
    if scene.rigidbody_world is None:
        bpy.ops.rigidbody.world_add()
    world = scene.rigidbody_world
    world.point_cache.frame_start, world.point_cache.frame_end = frame_start, frame_end
    world.substeps_per_frame = 10
    world.solver_iterations = 10
    return world


def make_rigid(obj, kind: str = "ACTIVE", mass: float = 1.0, friction: float = 0.6, shape: str = "CONVEX_HULL"):
    with bpy.context.temp_override(
        object=obj, active_object=obj, selected_objects=[obj], selected_editable_objects=[obj]
    ):
        bpy.ops.rigidbody.object_add(type=kind)
    obj.rigid_body.mass = mass
    obj.rigid_body.friction = friction
    obj.rigid_body.collision_shape = "BOX" if kind == "PASSIVE" else shape
    obj.rigid_body.collision_margin = 0.02
    return obj


def inertia_shock(scene, start: int, end: int, accel: float, direction_deg: float = 0.0) -> None:
    """A sudden stop of the ground = a pseudo-force on everything, proportional to mass,
    pointing the way things were moving. Rigid bodies feel it exactly like tilted gravity."""
    gx, gy = accel * math.cos(math.radians(direction_deg)), accel * math.sin(math.radians(direction_deg))
    scene.use_gravity = True
    scene.gravity = (0, 0, -9.81)
    scene.keyframe_insert("gravity", frame=max(1, start - 1))
    scene.gravity = (gx, gy, -9.81)
    scene.keyframe_insert("gravity", frame=start)
    scene.keyframe_insert("gravity", frame=end)
    scene.gravity = (0, 0, -9.81)
    scene.keyframe_insert("gravity", frame=end + 1)


def simulate(scene) -> None:
    """Step the simulation once from the start, so any frame can be rendered (and resumed)."""
    if scene.rigidbody_world is None:
        return
    for frame in range(scene.frame_start, scene.frame_end + 1):
        scene.frame_set(frame)
    scene.frame_set(scene.frame_start)


