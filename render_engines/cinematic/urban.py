def _sky(env: dict, scene) -> dict:
    preset = SKY_PRESETS[env.get("time_of_day", "day")]
    elevation, azimuth, sun_color, sun_strength, sky_strength, fill_color, fill_power = preset
    # Seafront shots look south over the water: keep the sun behind the camera unless told otherwise.
    azimuth = env.get("sun_azimuth", 330 if env.get("type") == "coast" else azimuth)
    sky, background = set_sky(
        scene, elevation, azimuth, strength=sky_strength, dust=env.get("haze", 0.6), sun_disc=0 < elevation < 10
    )
    sun = lights.sun("Sun", max(elevation, 1), azimuth, sun_color, sun_strength, softness_deg=2)
    fill = lights.area("Fill", (-8, -14, 9), (math.radians(60), 0, math.radians(-30)), fill_color, fill_power, size=12)
    return {
        "sky": sky,
        "sky_background": background,
        "sun": sun,
        "sun_strength": sun_strength,
        "sky_strength": sky_strength,
        "fill": fill,
        "azimuth": azimuth,
    }


def _shard_corner(jitter, cols: int, rows: int, a: int, b: int) -> tuple[float, float]:
    """Corner of a pre-cut glass shard; inner corners are jittered so the cracks look irregular."""
    jx, jz = jitter[a][b] if 0 < a < cols and 0 < b < rows else (0, 0)
    return (-0.7 + 1.4 * a / cols + jx * 0.5, -0.78 + 1.56 * b / rows + jz * 0.5)


def _hero_facade(urban: Urban, x0: float, width: float, floors: int, wall: str, rng, col) -> None:
    """Foreground building front with real glass panes (pre-cut into shards) that can shatter."""
    y = BUILDING_LINE - 0.02
    glass = materials.principled("hero_glass", "#9db6c8", roughness=0.04, metallic=0.2)
    frame_mat = _mat("hero_frame", "#e9e6df", roughness=0.5)
    bay = 2.6
    bays = int(width // bay)
    for floor in range(1, floors):
        for b in range(bays):
            cx = x0 + bay * (b + 0.5)
            cz = floor * 3.0 + 1.65
            compound(
                f"hero_frame_{floor}_{b}",
                [
                    (_box(1.5, 0.12, 0.08, (0, 0, 0.82)), frame_mat),
                    (_box(1.5, 0.12, 0.08, (0, 0, -0.82)), frame_mat),
                    (_box(0.08, 0.12, 1.7, (0.75, 0, 0)), frame_mat),
                    (_box(0.08, 0.12, 1.7, (-0.75, 0, 0)), frame_mat),
                ],
                (cx, y - 0.02, cz),
                col=col,
            )
            shards = []
            cols, rows = 3, 3
            jitter = [
                [(rng.uniform(-0.12, 0.12), rng.uniform(-0.12, 0.12)) for _ in range(rows + 1)] for _ in range(cols + 1)
            ]
            for i in range(cols):
                for j in range(rows):
                    quads = [
                        _shard_corner(jitter, cols, rows, a, b)
                        for a, b in ((i, j), (i + 1, j), (i + 1, j + 1), (i, j + 1))
                    ]
                    for tri in ((quads[0], quads[1], quads[2]), (quads[0], quads[2], quads[3])):
                        cxs = sum(p[0] for p in tri) / 3
                        czs = sum(p[1] for p in tri) / 3
                        bm = bmesh.new()
                        verts = [bm.verts.new((p[0] - cxs, 0, p[1] - czs)) for p in tri]
                        face = bm.faces.new(verts)
                        bmesh.ops.solidify(bm, geom=[face], thickness=0.02)
                        shard = objects.mesh_object(
                            f"shard_{floor}_{b}_{i}_{j}_{len(shards)}",
                            bm,
                            glass,
                            False,
                            location=(cx + cxs, y - 0.05, cz + czs),
                            col=col,
                        )
                        shards.append(shard)
            urban.panes.append(shards)


def build_city(env: dict, ctx, scene, seed: int) -> Urban:
    rng = random.Random(seed)
    urban = Urban()
    col = objects.collection("City")
    length = env.get("length", 90.0)
    coast = env.get("type") == "coast"
    style = env.get("style") if env.get("style") in CITY_STYLES else rng.choice(tuple(CITY_STYLES))
    widths, near_floors, far_floors, palette, awning_chance = CITY_STYLES[style]
    urban.style = style

    asphalt = materials.noise_ground("asphalt", "#2a2b2e", "#3a3b3f", scale=2.0, roughness=0.9, bump=0.1)
    concrete = materials.noise_ground("sidewalk", "#9c9a94", "#b3b0a8", scale=1.2, roughness=0.85, bump=0.1)
    paint = _mat("road_paint", "#f2f2ee", roughness=0.6)
    # The road sits one curb lower; sidewalks are at z = 0, where people walk.
    ground = objects.mesh_object("Road", _box(length * 2, ROAD_HALF * 2, 0.2, (0, 0, -CURB_H - 0.1)), asphalt, col=col)
    urban.static = [ground]
    for side in (1, -1):
        if coast and side < 0:
            continue
        walk = objects.mesh_object(
            f"Sidewalk_{side}",
            _box(length * 2, SIDEWALK + 0.4, 0.4, (0, side * (ROAD_HALF + (SIDEWALK + 0.4) / 2), -0.2)),
            concrete,
            col=col,
        )
        urban.static.append(walk)
        objects.mesh_object(
            f"Plinth_{side}", _box(length * 2, 40, 0.2, (0, side * (BUILDING_LINE + 20), -0.1)), concrete, col=col
        )
    for x in range(-int(length), int(length), 6):  # dashed centre line
        objects.mesh_object(f"dash_{x}", _box(3.0, 0.15, 0.01, (x + 1.5, 0, -CURB_H + 0.005)), paint, col=col)
    for i in range(8):  # zebra crossing at x = 10
        objects.mesh_object(f"zebra_{i}", _box(3.0, 0.5, 0.01, (10, -3.15 + i * 0.9, -CURB_H + 0.006)), paint, col=col)

    # Buildings: north side (and south side unless it is the seafront).
    hero_x0 = env.get("hero_x", -6.0)
    for side in (1, -1):
        if coast and side < 0:
            continue
        x = -length
        index = 0
        while x < length:
            width = rng.choice(widths)
            floors = rng.randint(*far_floors) if abs(x) > 20 else rng.randint(*near_floors)
            depth = rng.uniform(10, 16)
            wall = rng.choice(palette)
            is_hero = side == 1 and x <= hero_x0 < x + width
            mat = facade_material(f"facade_{side}_{index}", wall, seed + index)
            height = floors * 3.0 + 0.6
            y = side * (BUILDING_LINE + depth / 2)
            building = objects.mesh_object(
                f"building_{side}_{index}",
                _box(width - 0.3, depth, height, (x + width / 2, y, height / 2)),
                mat,
                col=col,
            )
            urban.facades.append(mat)
            urban.static.append(building)
            urban.buildings.append((building, side, is_hero))
            if style == "new_york":
                _billboards(urban, f"bb_{side}_{index}", x, width, side, height, rng, col)
            if style == "suburb":  # pitched roof
                roof = objects.mesh_object(
                    f"roof_{side}_{index}",
                    objects.cone(width * 0.62, 0.0, 2.2, 4, base_at_origin=True),
                    _mat(f"roof_{index % 3}", ("#8a3b2a", "#4a4f57", "#6b4a2e")[index % 3], 0.8),
                    location=(x + width / 2, y, height),
                    rotation=(0, 0, math.radians(45)),
                    scale=(1.0, depth / width, 1.0),
                    col=col,
                )
                urban.static.append(roof)
            if rng.random() < awning_chance:
                awning(
                    f"awning_{side}_{index}",
                    (x + width / 2, side * BUILDING_LINE - side * 0.02, 3.1),
                    width * 0.7,
                    rng.choice(("#b8372d", "#2d6b8a", "#3f7a35", "#d18a1f")),
                    col,
                )
            if is_hero:
                _hero_facade(urban, x + 0.4, width - 1.0, floors, wall, rng, col)
                # The hero building's facade shader keeps its windows off where real panes sit.
            x += width
            index += 1

    # Street furniture along both sidewalks.
    heads = []
    for side in (1, -1):
        if coast and side < 0:
            continue
        sy = side * (ROAD_HALF + 0.6)
        for x in range(-int(length) + 8, int(length), 16):
            _, head = street_lamp(f"lamp_{side}_{x}", (x, sy, 0.0), side, col)
            heads.append(head)
        for x in range(-int(length) + 14, int(length), 22):
            tree = street_tree(f"tree_{side}_{x}", (x, side * (ROAD_HALF + 1.4), 0.0), rng, col)
            urban.static.append(tree)
        for x in range(-int(length) + 4, int(length), 19):
            b = bench(f"bench_{side}_{x}", (x, side * (ROAD_HALF + 2.3), 0.0), 180 if side > 0 else 0, col)
            urban.loose.append((b, 40.0))
            bn = bin_(f"bin_{side}_{x}", (x + 2.5, side * (ROAD_HALF + 0.9), 0.0), col)
            urban.loose.append((bn, 15.0))
    urban.lamp_heads = list({id(h): h for h in heads}.values())
    traffic_light("traffic_light_n", (13.5, ROAD_HALF + 0.5, 0.0), col)
    if not coast:
        traffic_light("traffic_light_s", (6.5, -ROAD_HALF - 0.5, 0.0), col)

    # Parked and moving cars.
    for i in range(env.get("parked_cars", 8)):
        x = rng.uniform(-length * 0.6, length * 0.6)
        if 6 < x < 14:
            continue
        side = 1 if i % 2 else -1
        c = car(
            f"parked_{i}",
            (x, side * (ROAD_HALF - 1.1), -CURB_H),
            0 if side > 0 else 180,
            TAXI_YELLOW if style == "new_york" and rng.random() < 0.65 else rng.choice(CAR_COLORS),
            col,
        )
        urban.loose.append((c, 1200.0))

    if coast:
        _seafront(urban, env, length, col)
    urban.sky_refs = _sky(env, scene)
    night = env.get("time_of_day") == "night"
    for mat in urban.facades:
        mat.node_tree.nodes["Lights"].outputs[0].default_value = 0.45 if night else 0.0
    for head in urban.lamp_heads:
        head.node_tree.nodes["Principled BSDF"].inputs["Emission Strength"].default_value = 6.0 if night else 0.0
    return urban


def _billboards(urban: Urban, name: str, x0: float, width: float, side: int, height: float, rng, col) -> None:
    """Times Square: glowing screens with bold words on the street side of a tall building."""
    face_y = side * (BUILDING_LINE - 0.06)
    level = 4.5
    for k in range(rng.randint(1, 3)):
        h = rng.uniform(3.0, 6.0)
        if level + h > min(height - 1.0, 26.0):
            break
        w = rng.uniform(0.6, 0.92) * (width - 1.0)
        cx = x0 + width / 2 + rng.uniform(-0.5, 0.5)
        color = rng.choice(BILLBOARD_COLORS)
        screen = _mat(f"{name}_{k}_screen", color, roughness=0.4, emission=color, strength=1.4)
        objects.mesh_object(f"{name}_{k}", _box(w, 0.12, h, (cx, face_y, level + h / 2)), screen, col=col)
        _sign_text(
            f"{name}_{k}_txt",
            rng.choice(BILLBOARD_TEXTS),
            (cx, face_y - side * 0.1, level + h / 2),
            side,
            min(h * 0.35, w / 7),
            col,
        )
        level += h + rng.uniform(0.6, 2.0)


def _sign_text(name: str, text: str, center, side: int, size: float, col) -> None:
    curve = bpy.data.curves.new(name, "FONT")
    curve.body = text
    curve.size = size
    curve.extrude = 0.02
    curve.align_x, curve.align_y = "CENTER", "CENTER"
    obj = bpy.data.objects.new(name, curve)
    obj.location = center
    # Text lies in the XY plane facing +Z: stand it up facing the street.
    obj.rotation_euler = (math.radians(90), 0, 0 if side > 0 else math.pi)
    obj.data.materials.append(_mat("sign_white", "#ffffff", roughness=0.3, emission="#ffffff", strength=3.0))
    objects.link(obj, col)


def _seafront(urban: Urban, env: dict, length: float, col) -> None:
    """South side becomes a promenade, a railing, a beach and the sea."""
    stone = _mat("promenade", "#c9bfa9", roughness=0.8)
    sand = materials.noise_ground("sand", "#d8c48f", "#e6d6a8", scale=0.8, roughness=0.95, bump=0.2)
    rail = _mat("rail", "#e6e6e6", roughness=0.4, metallic=0.6)
    objects.mesh_object("Promenade", _box(length * 2, 5, 0.4, (0, -(ROAD_HALF + 2.5), -0.2)), stone, col=col)
    for x in range(-int(length), int(length), 2):
        objects.mesh_object(f"rail_post_{x}", _cyl(0.04, 1.0, (x, -(ROAD_HALF + 4.9), 0.65)), rail, col=col)
    objects.mesh_object("rail_bar", _cyl(0.05, length * 2, (0, -(ROAD_HALF + 4.9), 1.15), "X"), rail, col=col)
    objects.mesh_object("Beach", _box(length * 2, 30, 0.4, (0, -(ROAD_HALF + 20), -1.2)), sand, col=col)
    urban.water = water_body("Sea", (0, -(ROAD_HALF + 60), -1.0), (length * 2, 80), col)


def water_body(name: str, location, size, col=None):
    """Ocean surface: deep blue, glossy, with moving procedural waves (bump), opaque for speed."""
    mat = bpy.data.materials.new(f"{name}_water")
    mat.use_nodes = True
    nodes, links = mat.node_tree.nodes, mat.node_tree.links
    bsdf = nodes["Principled BSDF"]
    bsdf.inputs["Base Color"].default_value = hex_to_linear("#1d5c86")
    bsdf.inputs["Roughness"].default_value = 0.08
    bsdf.inputs["Coat Weight"].default_value = 0.6
    coord = nodes.new("ShaderNodeTexCoord")
    mapping = nodes.new("ShaderNodeMapping")
    mapping.name = "Waves"
    links.new(coord.outputs["Object"], mapping.inputs["Vector"])
    noise = nodes.new("ShaderNodeTexNoise")
    noise.inputs["Scale"].default_value = 0.35
    noise.inputs["Detail"].default_value = 6.0
    links.new(mapping.outputs["Vector"], noise.inputs["Vector"])
    bump = nodes.new("ShaderNodeBump")
    bump.inputs["Strength"].default_value = 0.6
    links.new(noise.outputs["Fac"], bump.inputs["Height"])
    links.new(bump.outputs["Normal"], bsdf.inputs["Normal"])
    foam = nodes.new("ShaderNodeValToRGB")
    foam.color_ramp.elements[0].position = 0.68
    foam.color_ramp.elements[0].color = (0, 0, 0, 1)
    foam.color_ramp.elements[1].position = 0.75
    links.new(noise.outputs["Fac"], foam.inputs["Fac"])
    mix = nodes.new("ShaderNodeMix")
    mix.data_type = "RGBA"
    mix.inputs["A"].default_value = hex_to_linear("#1d5c86")
    mix.inputs["B"].default_value = hex_to_linear("#e8f2f5")
    links.new(foam.outputs["Color"], mix.inputs["Factor"])
    links.new(mix.outputs["Result"], bsdf.inputs["Base Color"])
    plane = objects.mesh_object(name, _box(size[0], size[1], 2.0, (0, 0, -1.0)), mat, location=location, col=col)
    plane.visible_shadow = False
    return plane


def animate_waves(water, start: int, end: int, speed=(0.0, 0.6, 0.0)) -> None:
    mapping = water.active_material.node_tree.nodes["Waves"]
    socket = mapping.inputs["Location"]
    socket.default_value = (0, 0, 0)
    socket.keyframe_insert("default_value", frame=start)
    span = (end - start) / 24
    socket.default_value = (speed[0] * span, speed[1] * span, speed[2] * span)
    socket.keyframe_insert("default_value", frame=end)


def surge(urban: Urban, start: int, end: int, height: float, inland: float) -> None:
    """The sea comes ashore: the water body rises and advances into the street."""
    water = urban.water
    x, y, z = water.location
    key(water, "location", start, (x, y, z))
    key(water, "location", end, (x, y + inland, z + height))
    set_interpolation(water, "LINEAR")
    animate_waves(water, start, end, (0.4, 1.5, 0.3))


def shatter_windows(urban: Urban, start: int, fps: int, stagger: float = 0.25) -> None:
    """Glass panes break (rigid-body shards released, slightly staggered floor by floor)."""
    rng = random.Random(len(urban.panes))
    for k, shards in enumerate(urban.panes):
        frame = start + round(rng.uniform(0, stagger) * fps) + (k % 3)
        for shard in shards:
            shard.rigid_body.kinematic = True
            shard.rigid_body.keyframe_insert("kinematic", frame=1)
            shard.rigid_body.keyframe_insert("kinematic", frame=frame - 1)
            shard.rigid_body.kinematic = False
            shard.rigid_body.keyframe_insert("kinematic", frame=frame)


def lights_on(urban: Urban, start: int, end: int, windows: float = 0.45) -> None:
    for mat in urban.facades:
        socket = mat.node_tree.nodes["Lights"].outputs[0]
        socket.keyframe_insert("default_value", frame=start)
        socket.default_value = windows
        socket.keyframe_insert("default_value", frame=end)
    for head in urban.lamp_heads:
        socket = head.node_tree.nodes["Principled BSDF"].inputs["Emission Strength"]
        socket.keyframe_insert("default_value", frame=start)
        socket.default_value = 6.0
        socket.keyframe_insert("default_value", frame=end)


