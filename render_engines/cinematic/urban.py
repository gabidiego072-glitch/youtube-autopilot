# --- materials ---------------------------------------------------------------
def _math(nodes, links, op, a, b=None, value=None, clamp=False):
    node = nodes.new("ShaderNodeMath")
    node.operation = op
    node.use_clamp = clamp
    links.new(a, node.inputs[0])
    if b is not None:
        links.new(b, node.inputs[1])
    elif value is not None:
        node.inputs[1].default_value = value
    return node.outputs[0]


def facade_material(name: str, wall: str, seed: int, bay: float = 2.6, floor_h: float = 3.0):
    """Wall with a grid of windows and a shop-front ground floor, all in the shader. The 'Lights' value
    node turns random windows on (night); the 'Damage' node darkens broken windows."""
    mat = bpy.data.materials.new(name)
    mat.use_nodes = True
    nodes, links = mat.node_tree.nodes, mat.node_tree.links
    bsdf = nodes["Principled BSDF"]
    coord = nodes.new("ShaderNodeTexCoord")
    sep = nodes.new("ShaderNodeSeparateXYZ")
    links.new(coord.outputs["Object"], sep.inputs["Vector"])
    u = _math(nodes, links, "ADD", sep.outputs["X"], sep.outputs["Y"])
    z = sep.outputs["Z"]
    fu = _math(nodes, links, "FRACT", _math(nodes, links, "DIVIDE", u, value=bay))
    fz = _math(nodes, links, "FRACT", _math(nodes, links, "DIVIDE", z, value=floor_h))
    in_u = _math(
        nodes,
        links,
        "MULTIPLY",
        _math(nodes, links, "GREATER_THAN", fu, value=0.22),
        _math(nodes, links, "LESS_THAN", fu, value=0.78),
    )
    in_z = _math(
        nodes,
        links,
        "MULTIPLY",
        _math(nodes, links, "GREATER_THAN", fz, value=0.3),
        _math(nodes, links, "LESS_THAN", fz, value=0.82),
    )
    upper = _math(nodes, links, "GREATER_THAN", z, value=floor_h * 1.15)
    windows = _math(nodes, links, "MULTIPLY", _math(nodes, links, "MULTIPLY", in_u, in_z), upper)
    # Ground floor: wide shop windows.
    shop_u = _math(
        nodes,
        links,
        "LESS_THAN",
        _math(nodes, links, "FRACT", _math(nodes, links, "DIVIDE", u, value=bay * 2)),
        value=0.86,
    )
    shop_z = _math(
        nodes,
        links,
        "MULTIPLY",
        _math(nodes, links, "GREATER_THAN", z, value=0.35),
        _math(nodes, links, "LESS_THAN", z, value=floor_h * 0.85),
    )
    shop = _math(nodes, links, "MULTIPLY", shop_u, shop_z)
    glass = _math(nodes, links, "MAXIMUM", windows, shop, clamp=True)
    # Per-window random value for lit windows.
    cell = nodes.new("ShaderNodeCombineXYZ")
    links.new(_math(nodes, links, "FLOOR", _math(nodes, links, "DIVIDE", u, value=bay)), cell.inputs["X"])
    links.new(_math(nodes, links, "FLOOR", _math(nodes, links, "DIVIDE", z, value=floor_h)), cell.inputs["Y"])
    cell.inputs["Z"].default_value = seed
    rnd = nodes.new("ShaderNodeTexWhiteNoise")
    rnd.noise_dimensions = "3D"
    links.new(cell.outputs["Vector"], rnd.inputs["Vector"])
    lights_value = nodes.new("ShaderNodeValue")
    lights_value.name = "Lights"
    lights_value.outputs[0].default_value = 0.0
    lit = _math(
        nodes, links, "MULTIPLY", _math(nodes, links, "LESS_THAN", rnd.outputs["Value"], lights_value.outputs[0]), glass
    )
    mix = nodes.new("ShaderNodeMix")
    mix.data_type = "RGBA"
    mix.inputs["A"].default_value = hex_to_linear(wall)
    mix.inputs["B"].default_value = hex_to_linear("#1c2a38")
    links.new(glass, mix.inputs["Factor"])
    links.new(mix.outputs["Result"], bsdf.inputs["Base Color"])
    rough = nodes.new("ShaderNodeMapRange")
    rough.inputs["To Min"].default_value = 0.85
    rough.inputs["To Max"].default_value = 0.08
    links.new(glass, rough.inputs["Value"])
    links.new(rough.outputs["Result"], bsdf.inputs["Roughness"])
    bsdf.inputs["Emission Color"].default_value = hex_to_linear("#ffcf8a")
    links.new(_math(nodes, links, "MULTIPLY", lit, value=3.0), bsdf.inputs["Emission Strength"])
    return mat


def _mat(name, color, roughness=0.6, metallic=0.0, emission=None, strength=0.0):
    return materials.principled(
        name, color, roughness=roughness, metallic=metallic, emission=emission, emission_strength=strength
    )


# --- compound meshes --------------------------------------------------------------
def compound(name: str, parts: list, location=(0, 0, 0), rotation=(0, 0, 0), col=None, smooth=False):
    """One object from several (bmesh, material) parts; keeps per-part materials."""
    mesh = bpy.data.meshes.new(name)
    total = bmesh.new()
    slots: list = []
    for bm, mat in parts:
        if mat not in slots:
            slots.append(mat)
        index = slots.index(mat)
        tmp = bpy.data.meshes.new("_tmp")
        bm.to_mesh(tmp)
        bm.free()
        before = len(total.faces)
        total.from_mesh(tmp)
        total.faces.ensure_lookup_table()
        for face in total.faces[before:]:
            face.material_index = index
        bpy.data.meshes.remove(tmp)
    total.to_mesh(mesh)
    total.free()
    for mat in slots:
        mesh.materials.append(mat)
    if smooth:
        mesh.polygons.foreach_set("use_smooth", [True] * len(mesh.polygons))
    obj = bpy.data.objects.new(name, mesh)
    obj.location, obj.rotation_euler = location, rotation
    return objects.link(obj, col)


def _box(sx, sy, sz, at=(0, 0, 0)):
    return objects.transform(objects.box(sx, sy, sz), Matrix.Translation(Vector(at)))


def _cyl(r, h, at=(0, 0, 0), axis="Z", segments=12):
    bm = objects.cone(r, r, h, segments, base_at_origin=False)
    rot = {
        "Z": Matrix.Identity(4),
        "X": Matrix.Rotation(math.pi / 2, 4, "Y"),
        "Y": Matrix.Rotation(math.pi / 2, 4, "X"),
    }
    return objects.transform(bm, Matrix.Translation(Vector(at)) @ rot[axis])


